export type IconName = keyof typeof glyphs;

const normalize = (g: Glyph | string | string[]): Glyph =>
  typeof g === "string" || Array.isArray(g) ? { d: g } : g;

export function Icon({
  name,
  size = 20,
  strokeWidth = 1.75,
  className,
  title,
  ...rest
}: {
  name: string;
  size?: number | string;
  strokeWidth?: number;
  title?: string;
} & Omit<SVGProps<SVGSVGElement>, "name">) {
  const glyph = normalize(glyphs[name] ?? glyphs.grid);
  const paths = Array.isArray(glyph.d) ? glyph.d : [glyph.d];
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={glyph.fill ? "currentColor" : "none"}
      stroke={glyph.fill ? "none" : "currentColor"}
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : true}
      focusable="false"
      {...rest}
    >
      {title ? <title>{title}</title> : null}
      {paths.map((d, i) => (
        <path key={i} d={d} />
      ))}
    </svg>
  );
}

/*
 * Rating row shared by the product card, the product page and reviews.
 * Half stars are real halves rather than a rounded-up whole star, so a 3.4
 * average does not read as 3.5 on the card and 3.4 in the summary.
 */
export function Stars({
  value,
  size = 12,
  className = "",
}: {
  value: number;
  size?: number;
  className?: string;
}) {
  const rounded = Math.round(value * 2) / 2;
  return (
    <span
      className={`inline-flex items-center gap-px text-star ${className}`}
      aria-hidden="true"
    >
      {[1, 2, 3, 4, 5].map((i) => (
        <Icon
          key={i}
          size={size}
          name={
            rounded >= i ? "starFilled" : rounded >= i - 0.5 ? "starHalf" : "star"
          }
          className={rounded >= i - 0.5 ? undefined : "text-ink-faint"}
        />
      ))}
    </span>
  );
}
