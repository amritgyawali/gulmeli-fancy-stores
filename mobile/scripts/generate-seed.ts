/*
 * Writes the catalogue SQL from src/data/catalog.ts:
 *
 *   supabase/seed.sql             sample products for a fresh database
 *   supabase/clothing-catalog.sql switches a live store to the clothing
 *                                 catalogue through the dashboard records
 *
 *   npm run backend:seed
 */
import { writeFileSync } from "node:fs";
import { products } from "../src/data/catalog.ts";
import { CATEGORY_BLURBS, CLOTHING_CATEGORIES } from "../src/data/clothing.ts";
import { seedVariants, storefrontDetails } from "../src/admin/core/seed.ts";
import { slugify } from "../src/admin/core/ids.ts";
import hosted from "../src/data/hosted-media.json" with { type: "json" };

const sql = (value: unknown) =>
  value == null ? "null" : `'${String(value).replaceAll("'", "''")}'`;
const photos = hosted as Record<string, { url: string; illustrative?: boolean }>;
/* The hosted (Cloudinary) photo for products that reuse one. */
const photoOf = (imageKey?: string) => (imageKey ? photos[imageKey]?.url : undefined);

/* ------------------------------------------------------------- seed.sql */

const rows = products.map((p, index) => {
  const { id, name, price, stock, category, group, imageUrl, ...details } = p;
  return `(${[id, name, price, stock, category, group, imageUrl ?? photoOf(p.imageKey), JSON.stringify(details), index].map(sql).join(", ")})`;
});
writeFileSync(
  new URL("../supabase/seed.sql", import.meta.url),
  `-- SAMPLE clothing inventory. Review prices/stock before accepting real orders.\n-- Generated by npm run backend:seed. Safe to rerun: existing product records are not overwritten.\ninsert into public.products(id,name,price,stock,category,product_group,image_url,details,sort_order) values\n${rows.join(",\n")}\non conflict (id) do nothing;\n`,
);

/* ------------------------------------------------- clothing-catalog.sql */

const now = "2026-10-17T00:00:00.000Z";
const categories = CLOTHING_CATEGORIES.map((name, index) => ({
  id: `cat_${slugify(name)}`,
  name,
  slug: slugify(name),
  parentId: null,
  description: CATEGORY_BLURBS[name],
  image: "",
  icon: "",
  banner: "",
  sortOrder: index,
  enabled: true,
  featured: index < 4,
  offerText: "",
  filters: ["price", "size", "color", "brand", "rating", "availability", "material"],
  seoTitle: `${name} clothing online in Nepal`,
  seoDescription: `Shop ${name.toLowerCase()} with cash on delivery and easy size exchanges.`,
  seoKeywords: [name.toLowerCase(), "clothing", "Nepal"],
  searchable: true,
  createdAt: now,
  updatedAt: now,
  deletedAt: null,
  revision: 1,
}));

const documents = products.map((p, index) => {
  const sku = `GFS-${String(index + 1).padStart(4, "0")}`;
  const photo = p.imageUrl ?? photoOf(p.imageKey);
  return {
    id: p.id,
    name: p.name,
    slug: slugify(p.name).slice(0, 60),
    sku,
    barcode: "",
    productCode: p.id,
    shortDescription: p.highlights?.join(" · ") ?? "",
    description: p.description ?? "",
    images: photo ? [photo] : [],
    imageAlt: p.name,
    price: p.originalPrice && p.originalPrice > p.price ? p.originalPrice : p.price,
    salePrice: p.originalPrice && p.originalPrice > p.price ? p.price : null,
    compareAtPrice: null,
    taxClass: "standard",
    categoryId: `cat_${slugify(p.category)}`,
    categoryName: p.category,
    brand: p.brand ?? "",
    collectionIds: [],
    tags: [p.category, p.gender].filter(Boolean).map((t) => String(t).toLowerCase()),
    productType: "physical",
    stock: p.stock,
    lowStockThreshold: 5,
    warehouse: "Main",
    unlimitedStock: false,
    allowBackorder: false,
    minPurchaseQty: 1,
    maxPurchaseQty: 10,
    variants: seedVariants(p, sku),
    specifications: [
      ["Fabric", p.fabric],
      ["Fit", p.fit],
      ["For", p.gender],
      ["Sizes", p.sizes?.join(", ")],
    ]
      .filter((row): row is [string, string] => Boolean(row[1]))
      .map(([label, value]) => ({ label, value })),
    features: p.highlights ?? [],
    careInstructions: p.care?.join("\n") ?? "",
    details: {
      ...storefrontDetails(p),
      ...(photo && photos[p.imageKey ?? ""]?.illustrative ? { imageIllustrative: true } : {}),
    },
    sortOrder: index,
    searchBoost: 1,
    badge: p.badge ?? "",
    featured: index % 7 === 0,
    bestseller: (p.sold ?? 0) > 800,
    newArrival: index % 5 === 0,
    trending: Number.parseFloat(p.rating ?? "0") >= 4.6,
    storefrontGroup: p.group,
    searchable: true,
    status: p.group === "unavailable" ? "draft" : "published",
    publishAt: null,
    unpublishAt: null,
    createdAt: now,
    updatedAt: now,
    deletedAt: null,
    revision: 1,
  };
});

const json = (value: unknown) => `${sql(JSON.stringify(value))}::jsonb`;
const ids = documents.map((d) => sql(d.id)).join(",");

writeFileSync(
  new URL("../supabase/clothing-catalog.sql", import.meta.url),
  `-- Switches the live store to the clothing catalogue. Generated by
-- npm run backend:seed from src/data/catalog.ts. Run it once in the Supabase
-- SQL editor (or: npm run backend:sql -- supabase/clothing-catalog.sql),
-- after supabase/deploy.sql.
--
-- * Adds the clothing departments (Men, Women, Kids, Ethnic Wear, Winter Wear,
--   Activewear, Accessories).
-- * Adds the clothing products, with sizes, colours, fabric, fit and care.
--   Products that already exist are left as they are, so edits made in the
--   dashboard survive a rerun.
-- * Archives every other product, so groceries and electronics leave the
--   storefront. Archived products stay in the dashboard and can be restored.
-- * Updates the storefront wording that still has the old general-store
--   default.
-- Orders, customers and their history are not touched.
begin;

insert into public.admin_data(collection,id,document)
select 'categories', value->>'id', value from jsonb_array_elements(${json(categories)})
on conflict (collection,id) do nothing;

insert into public.admin_data(collection,id,document)
select 'products', value->>'id', value from jsonb_array_elements(${json(documents)})
on conflict (collection,id) do nothing;

-- Everything that is not in the clothing catalogue leaves the storefront.
update public.admin_data
   set document = document || jsonb_build_object('status','archived','updatedAt',now(),
         'revision',coalesce((document->>'revision')::int,0)+1),
       updated_at = now()
 where collection = 'products'
   and id not in (${ids})
   and document->>'status' is distinct from 'archived';
update public.products set active = false where id not in (${ids});

-- Old departments are switched off; their products are archived above.
update public.admin_data
   set document = document || jsonb_build_object('enabled',false,'updatedAt',now()), updated_at = now()
 where collection = 'categories'
   and id not in (${categories.map((c) => sql(c.id)).join(",")})
   and coalesce((document->>'enabled')::boolean,true);

-- Wording that still reads like a general store.
update public.app_config set published = jsonb_set(published,'{branding,tagline}','"Fashion for every season, delivered."')
 where published#>>'{branding,tagline}' = 'Everyday fancy goods, delivered.';
update public.app_config set published = jsonb_set(published,'{header,searchPlaceholder}','"Search shirts, kurtis, jackets…"')
 where published#>>'{header,searchPlaceholder}' = 'Search for products';
update public.app_config set published = jsonb_set(published,'{text,homeHeading}','"New season styles for the whole family"')
 where published#>>'{text,homeHeading}' = 'Shop with Gulmeli Fancy Stores';

commit;
`,
);
console.log(
  `Prepared ${rows.length} sample products in supabase/seed.sql and the clothing catalogue in supabase/clothing-catalog.sql.`,
);
